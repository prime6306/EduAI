"""
Builds the final performance report from every scored turn in a session.

Design choice kept from the original build: the *readiness band* is a
plain, published threshold table, not another LLM call — deterministic
and auditable, so two candidates with the same overall score always get
the same label. Competency scores are a plain average of the tagged
per-answer scores. The prep plan is generated by Arjun's persona
(Gemini) from the weakest-scored answers and the missing-skills list.
"""
from collections import defaultdict

from . import prompts, personas, llm_router

READINESS_BANDS = [
    (80, "Strong Candidate", "success", "Demonstrates strong readiness for the role."),
    (65, "Interview Ready", "info", "Can reasonably attempt the interview."),
    (50, "Needs Preparation", "warning", "Some important gaps remain."),
    (0, "Not Ready", "danger", "Significant preparation required."),
]

_ASSESSMENT_LABELS = [(8, "Excellent"), (6, "Good"), (4, "Adequate"), (0, "Weak")]

COMPETENCY_LABELS = {
    "role_fit": "Role Fit",
    "technical_knowledge": "Technical Knowledge",
    "problem_solving": "Problem Solving",
    "communication": "Communication",
    "confidence": "Confidence",
    "depth_of_understanding": "Depth of Understanding",
    "behavioural_fit": "Behavioural Fit",
}

INTERVIEWER_NAMES = {
    personas.RECRUITER_A: personas.get(personas.RECRUITER_A)["name"],
    personas.RECRUITER_B: personas.get(personas.RECRUITER_B)["name"],
}


def _assessment_label(score):
    if score is None:
        return ""
    for threshold, label in _ASSESSMENT_LABELS:
        if score >= threshold:
            return label
    return _ASSESSMENT_LABELS[-1][1]


def _readiness(score: float) -> dict:
    for threshold, label, tone, description in READINESS_BANDS:
        if score >= threshold:
            return {"label": label, "tone": tone, "description": description}
    _, label, tone, description = READINESS_BANDS[-1]
    return {"label": label, "tone": tone, "description": description}


def build_report(session: dict) -> dict:
    turns = session.get("turns", [])
    scored = [t for t in turns if t.get("quality_score") is not None]

    overall_score = round(sum(t["quality_score"] for t in scored) / len(scored) * 10, 1) if scored else 0.0

    by_competency = defaultdict(list)
    for t in scored:
        tag = t.get("competency_tag") or "role_fit"
        by_competency[tag].append(t["quality_score"])
    competency_scores = {
        COMPETENCY_LABELS.get(tag, tag): round(sum(v) / len(v) * 10, 1)
        for tag, v in by_competency.items()
    }

    ranked = sorted(scored, key=lambda t: t["quality_score"])
    weaknesses = [{"question": t["question"], "issue": t.get("what_could_be_better", "")} for t in ranked[:3]]
    strengths = [{"question": t["question"], "why": t.get("what_was_good", "")} for t in reversed(ranked[-3:])]

    question_feedback = [
        {
            "level": t["level"],
            "interviewer": INTERVIEWER_NAMES.get(t["interviewer"], t["interviewer"]),
            "question": t["question"],
            "answer": t.get("answer", ""),
            "quality_score": t.get("quality_score"),
            "assessment": _assessment_label(t.get("quality_score")),
            "competency": COMPETENCY_LABELS.get(t.get("competency_tag", ""), t.get("competency_tag", "")),
            "what_was_good": t.get("what_was_good", ""),
            "what_could_be_better": t.get("what_could_be_better", ""),
            "ideal_direction": t.get("ideal_direction", ""),
        }
        for t in turns
    ]

    resume_analysis = session.get("resume_analysis", {}) or {}
    missing_skills = resume_analysis.get("missing_skills", [])
    weak_topics = [w["issue"] for w in weaknesses if w["issue"]]

    system, user = prompts.prep_plan_prompt(
        session.get("jd_analysis", {}), weak_topics, missing_skills, personas.RECRUITER_B,
    )
    prep = llm_router.complete_json("gemini", system, user, temperature=0.5)

    return {
        "overall_score": overall_score,
        "readiness": _readiness(overall_score),
        "competency_scores": competency_scores,
        "strengths": strengths,
        "weaknesses": weaknesses,
        "question_feedback": question_feedback,
        "preparation_plan": prep.get("priorities", []),
        "job_fit_percent": (session.get("job_fit") or {}).get("job_fit_percent"),
        "total_questions": len(turns),
    }
